import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { MeshoptEncoder } from "meshoptimizer/encoder";
import { MeshoptDecoder } from "three/addons/libs/meshopt_decoder.module.js";
import * as THREE from "three";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { format } from "prettier";
import { withFooterStroke } from "./footer-stroke-progress.mjs";

const root = new URL("../", import.meta.url);
const output = new URL("public/models/optimized/", root);
await mkdir(output, { recursive: true });
await Promise.all([MeshoptEncoder.ready, MeshoptDecoder.ready]);
const manifest = {};
let helloBounds;

for (const name of ["hello", "thank-you"]) {
  const sourceModel = await readFile(
    new URL(`public/models/${name}.glb`, root),
  );
  const original =
    name === "thank-you" ? withFooterStroke(sourceModel) : sourceModel;
  const jsonLength = original.readUInt32LE(12);
  const json = JSON.parse(original.subarray(20, 20 + jsonLength).toString());
  const source = original.subarray(28 + jsonLength);
  const packed = [];
  let length = 0;
  for (let index = 0; index < json.bufferViews.length; index++) {
    const view = json.bufferViews[index];
    const accessor = json.accessors.find((item) => item.bufferView === index);
    if (
      !accessor ||
      json.accessors.filter((item) => item.bufferView === index).length !== 1
    )
      throw new Error("Expected one accessor per model buffer view");
    const stride = view.byteStride ?? (accessor.componentType === 5123 ? 2 : 4);
    const mode = view.target === 34963 ? "INDICES" : "ATTRIBUTES";
    const bytes = source.subarray(
      view.byteOffset ?? 0,
      (view.byteOffset ?? 0) + view.byteLength,
    );
    const encoded = MeshoptEncoder.encodeGltfBuffer(
      bytes,
      accessor.count,
      stride,
      mode,
      0,
    );
    const restored = new Uint8Array(bytes.length);
    MeshoptDecoder.decodeGltfBuffer(
      restored,
      accessor.count,
      stride,
      encoded,
      mode,
      "NONE",
    );
    if (!bytes.equals(Buffer.from(restored)))
      throw new Error(`${name}: non-lossless buffer ${index}`);
    const padding = Buffer.alloc((4 - (length % 4)) % 4);
    packed.push(padding);
    length += padding.length;
    view.buffer = 1;
    view.extensions = {
      EXT_meshopt_compression: {
        buffer: 0,
        byteOffset: length,
        byteLength: encoded.length,
        byteStride: stride,
        count: accessor.count,
        mode,
        filter: "NONE",
      },
    };
    packed.push(Buffer.from(encoded));
    length += encoded.length;
  }
  const binary = Buffer.concat([
    ...packed,
    Buffer.alloc((4 - (length % 4)) % 4),
  ]);
  json.buffers = [
    { byteLength: binary.length },
    {
      byteLength: json.buffers[0].byteLength,
      extensions: { EXT_meshopt_compression: { fallback: true } },
    },
  ];
  json.extensionsUsed = [
    ...new Set([...(json.extensionsUsed ?? []), "EXT_meshopt_compression"]),
  ];
  json.extensionsRequired = [
    ...new Set([...(json.extensionsRequired ?? []), "EXT_meshopt_compression"]),
  ];
  const text = Buffer.from(JSON.stringify(json));
  const jsonChunk = Buffer.concat([
    text,
    Buffer.alloc((4 - (text.length % 4)) % 4, 32),
  ]);
  const header = Buffer.alloc(20);
  header.writeUInt32LE(0x46546c67, 0);
  header.writeUInt32LE(2, 4);
  header.writeUInt32LE(28 + jsonChunk.length + binary.length, 8);
  header.writeUInt32LE(jsonChunk.length, 12);
  header.writeUInt32LE(0x4e4f534a, 16);
  const binaryHeader = Buffer.alloc(8);
  binaryHeader.writeUInt32LE(binary.length, 0);
  binaryHeader.writeUInt32LE(0x004e4942, 4);
  const optimized = Buffer.concat([header, jsonChunk, binaryHeader, binary]);
  const loader = new GLTFLoader().setMeshoptDecoder(MeshoptDecoder);
  const gltf = await loader.parseAsync(
    optimized.buffer.slice(
      optimized.byteOffset,
      optimized.byteOffset + optimized.byteLength,
    ),
    "",
  );
  if (name === "hello") {
    const group = new THREE.Group();
    group.scale.setScalar(1.7);
    group.position.set(2, -0.4, 0);
    group.rotation.set(0, 0.07, 0);
    gltf.scene.traverse((object) => {
      if (object.isMesh) group.add(new THREE.Mesh(object.geometry));
    });
    const bounds = new THREE.Box3().setFromObject(group);
    helloBounds = { min: bounds.min.toArray(), max: bounds.max.toArray() };
  }
  const hash = createHash("sha256")
    .update(optimized)
    .digest("hex")
    .slice(0, 12);
  const filename = `${name}.${hash}.glb`;
  await writeFile(new URL(filename, output), optimized);
  manifest[name === "hello" ? "hello" : "footer"] =
    `/models/optimized/${filename}`;
  console.log(
    `${name}: ${original.length} -> ${optimized.length} bytes; every decoded buffer matches exactly`,
  );
}

await writeFile(
  new URL("src/data/glassAssets.ts", root),
  await format(
    `// Generated by scripts/optimize-glass-models.mjs.\nexport const GLASS_ASSETS = ${JSON.stringify({ ...manifest, helloBounds }, null, 2)} as const;\n`,
    { parser: "typescript" },
  ),
);
console.log(
  `Manifest: ${fileURLToPath(new URL("src/data/glassAssets.ts", root))}`,
);
