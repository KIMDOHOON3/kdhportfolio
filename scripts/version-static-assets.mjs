import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

/**
 * npm run dev/build generate these automatically. After replacing source files
 * during a running dev session, run npm run assets:version to update URLs.
 * Content addresses are permanent: keep old versions for old tabs/rollbacks.
 */
export function versionStaticAssets({
  root = projectRoot,
  check = false,
} = {}) {
  const update = (relative, content) => {
    const target = path.join(root, relative);
    const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);
    if (existsSync(target) && readFileSync(target).equals(bytes)) return;
    if (check)
      throw new Error(
        `Stale asset output: ${relative}. Run npm run assets:version.`,
      );
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, bytes);
  };
  const fingerprint = (directory, file, category) => {
    const bytes = readFileSync(path.join(root, directory, file));
    const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
    const extension = path.extname(file);
    const name = `${path.basename(file, extension)}.${hash}${extension}`;
    const url = `/assets/${category}/${name}`;
    update(`public${url}`, bytes);
    return url;
  };
  const gallery = {};
  for (const file of readdirSync(
    path.join(root, "public/projects/gallery"),
  ).sort()) {
    if (/^\d+\.webp$/.test(file))
      gallery[Number(path.basename(file, ".webp"))] = fingerprint(
        "public/projects/gallery",
        file,
        "gallery",
      );
  }
  const fonts = {};
  for (const file of readdirSync(path.join(root, "public/font")).sort()) {
    if (file.endsWith(".woff2"))
      fonts[file] = fingerprint("public/font", file, "fonts");
  }
  if (!Object.keys(gallery).length || !Object.keys(fonts).length)
    throw new Error("No gallery images or WOFF2 fonts found.");
  update(
    "src/data/staticAssets.ts",
    [
      "// Generated by scripts/version-static-assets.mjs. Do not edit URLs by hand.",
      `export const GALLERY_ASSETS: Readonly<Record<number, string>> = ${JSON.stringify(gallery, null, 2)};`,
      `export const FONT_ASSETS = ${JSON.stringify(fonts, null, 2)} as const;`,
      "",
    ].join("\n"),
  );
  update(
    "src/styles/_asset-urls.scss",
    [
      '// Generated by scripts/version-static-assets.mjs.\n@use "sass:map";',
      "$font-urls: (",
      ...Object.entries(fonts).map(([file, url]) => `  "${file}": "${url}",`),
      ");",
      "@function font-url($file) {",
      "  @if not map.has-key($font-urls, $file) {",
      '    @error "Unknown font asset: #{$file}. Run npm run assets:version.";',
      "  }",
      '  @return url("#{map.get($font-urls, $file)}");',
      "}",
      "",
    ].join("\n"),
  );
  return { gallery, fonts };
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const result = versionStaticAssets({
    check: process.argv.includes("--check"),
  });
  console.log(
    `Versioned ${Object.keys(result.gallery).length} gallery images and ${Object.keys(result.fonts).length} fonts.`,
  );
}
