"""Build initial-copy subsets; original fonts remain the Unicode fallback.

Run after copy changes with Python + fonttools[woff]==4.67.0.
The derivative uses a new internal name as required by the bundled OFL.
"""
from pathlib import Path
from html import unescape
import re
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
characters = set(range(32, 127))
for path in sorted((root / "src").rglob("*")):
    if path.suffix in {".ts", ".tsx", ".scss"}:
        content = path.read_text(encoding="utf-8")
        characters.update(map(ord, unescape(content)))
        # Button labels use escaped nonbreaking spaces, absent as literal glyphs.
        characters.update(int(value, 16) for value in re.findall(r"\\u([0-9a-fA-F]{4})", content))


def unicode_ranges(points):
    ranges = []
    start = end = None
    for point in sorted(points):
        if end is not None and point == end + 1:
            end = point
        else:
            if start is not None:
                ranges.append((start, end))
            start = end = point
    if start is not None:
        ranges.append((start, end))
    return ",".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in ranges
    )


css = ["// Generated by scripts/subset-portfolio-fonts.py. Keep original OFL files.\n"]
for weight in ["Regular", "Bold"]:
    source = root / f"public/font/Pretendard-{weight}.woff2"
    font = TTFont(source)
    original_points = set(font.getBestCmap())
    points = characters.intersection(original_points)
    options = subset.Options()
    options.layout_features = ["*"]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    names = {
        1: "Portfolio Sans",
        2: weight,
        3: f"Portfolio Sans {weight} subset 1",
        4: f"Portfolio Sans {weight}",
        6: f"PortfolioSans-{weight}",
        16: "Portfolio Sans",
        17: weight,
    }
    for record in font["name"].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    # Some supplied originals omit a family name. Add complete derivative
    # metadata instead of only renaming the records that happen to exist.
    names[0] = "Copyright (c) 2021 Kil Hyung-jin; 2014-2021 Adobe; 2016 Inter Project Authors; 2021 M+ FONTS Project Authors."
    names[13] = (root / "public/font/Pretendard-OFL.txt").read_text(encoding="utf-8")
    for name_id, value in names.items():
        font["name"].setName(value, name_id, 3, 1, 0x409)
    target = root / f"public/font/PortfolioSans-{weight}.woff2"
    font.flavor = "woff2"
    font.save(target)
    # Disjoint ranges avoid downloading the original for spaces/symbols that
    # the supplied font itself does not support. New supported characters
    # outside the subset transparently request the complete original font.
    for filename, ranges in [
        (source.name, unicode_ranges(original_points - points)),
        (target.name, unicode_ranges(points)),
    ]:
        css.append(
            "@font-face {\n"
            f'  font-family: "Pretendard-{weight}";\n'
            "  font-style: normal;\n"
            "  font-display: swap;\n"
            f'  src: url("/font/{filename}") format("woff2");\n'
            + (f"  unicode-range: {ranges};\n" if ranges else "")
            + "}\n"
        )
    print(f"{weight}: {source.stat().st_size} -> {target.stat().st_size} bytes; {len(points)} characters")

(root / "src/app/styles/_pretendard.scss").write_text("\n".join(css), encoding="utf-8")
